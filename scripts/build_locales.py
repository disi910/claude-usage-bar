def main():
    base_keys = set(TRANSLATIONS["en"])
    errors = []
    for locale, strings in TRANSLATIONS.items():
        missing = base_keys - set(strings)
        extra = set(strings) - base_keys
        if missing:
            errors.append(f"{locale}: missing keys {sorted(missing)}")
        if extra:
            errors.append(f"{locale}: unknown keys {sorted(extra)}")
        if len(strings.get("extDesc", "")) > 132:
            errors.append(f"{locale}: extDesc over 132 chars ({len(strings['extDesc'])})")
        # Chrome caps the manifest name at 75 chars; the store shows ~45 in
        # search results, so keep the brand up front and keywords after the colon.
        if len(strings.get("extName", "")) > 75:
            errors.append(f"{locale}: extName over 75 chars ({len(strings['extName'])})")
        for key, names in PLACEHOLDER_KEYS.items():
            for name in names:
                if f"${name.upper()}$" not in strings.get(key, ""):
                    errors.append(f"{locale}: {key} missing ${name.upper()}$ placeholder")
    if errors:
        print("\n".join(errors), file=sys.stderr)
        sys.exit(1)

    for locale, strings in TRANSLATIONS.items():
        out = {}
        for key, message in strings.items():
            entry = {"message": message}
            if key in PLACEHOLDER_KEYS:
                entry["placeholders"] = {
                    name: {"content": f"${i}"}
                    for i, name in enumerate(PLACEHOLDER_KEYS[key], start=1)
                }
            out[key] = entry
        dest = ROOT / "_locales" / locale / "messages.json"
        dest.parent.mkdir(parents=True, exist_ok=True)
        dest.write_text(json.dumps(out, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
        print(f"wrote {dest.relative_to(ROOT)} ({len(out)} keys)")


if __name__ == "__main__":
    main()
